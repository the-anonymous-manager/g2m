// Regenerates lib/og-fonts.generated.ts from the Inter files in assets/fonts/.
//
// The og-image routes need these fonts' raw bytes at request time, on hosts with no real filesystem (Cloudflare
// Workers included), so they can't be read off disk or resolved by path at runtime. Embedding them as base64
// constants in the server bundle sidesteps that entirely: by the time a request comes in, the bytes are already in
// memory, on every host. Run this again only if the font files in assets/fonts/ change.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const dir = join(root, 'assets', 'fonts');
const regular = readFileSync(join(dir, 'Inter-Regular.otf')).toString('base64');
const bold = readFileSync(join(dir, 'InterDisplay-Bold.otf')).toString('base64');

const out = `// Generated by scripts/generate-og-fonts.mjs from assets/fonts/*.otf. Do not edit by hand; re-run that script
// if the font files change.
export const INTER_REGULAR_BASE64 = '${regular}';
export const INTER_BOLD_BASE64 = '${bold}';
`;

writeFileSync(join(root, 'lib', 'og-fonts.generated.ts'), out);
console.log(`Wrote lib/og-fonts.generated.ts (${((regular.length + bold.length) / 1024 / 1024).toFixed(1)} MB of base64).`);
